-- Writes AllTheThings (MIT) rules into a source folder for build_questcoords.lua: breadcrumbs.lua and attRules.lua.
--
--   lua5.1 tools/build_att_rules.lua <AllTheThings db folder> <source folder>
--
-- attRules.lua holds each quest's level range, the quests no character can be offered today with the reason (the Scourge
-- Invasion still runs on Season of Discovery), the dailies and the faction AllTheThings gives a quest. Loaded through
-- dofile with no arguments it returns the Forever writer, which build_forever_supplement.lua calls with --att.

local here = debug.getinfo(1, "S").source:match("^@(.*[/\\])") or "tools/"

-- The reasons build_questcoords.lua emits and Modules/MapPOI/Available.lua reads.
local NOT_IN_GAME, EVENT, INVASION, UNRELEASED = 1, 2, 3, 4

-- ATT's release phases with no build that opens them, which its own filter hides by default (src/Classes/base.lua).
local EVENT_PHASES = { [1501] = "war effort", [1502] = "war effort", [1503] = "war effort", [1701] = "Dark Portal opening" }
local INVASION_PHASES = { [1601] = true, [2108] = true }
-- An Era quest in one of these is hidden on WoW Forever only while ATT's Forever data leaves it out.
local LATE_PHASES = { [13] = true, [14] = true, [15] = true, [16] = true }

local function labelFor(dir)
    local folder = dir:gsub("[/\\]+$", ""):match("([^/\\]+)$") or dir
    local toc = io.open(dir .. "/../../AllTheThings.toc", "rb")
    local version = toc and toc:read("*a"):match("## Version:%s*([^\r\n]+)")
    if toc then toc:close() end
    return version and ("%s, db/%s"):format(version, folder) or ("db/" .. folder)
end

local function sortedKeys(t)
    local keys = {}
    for k in pairs(t) do keys[#keys + 1] = k end
    table.sort(keys)
    return keys
end

-- The event first, so a war effort quest ATT's TBC data also calls removed gives the same reason on every client.
local function copyCode(c, raids)
    if EVENT_PHASES[c.phase] then return EVENT end
    if INVASION_PHASES[c.phase] then return INVASION end
    if c.unobtainable == 1 or c.unobtainable == 2 then return NOT_IN_GAME end
    if raids and LATE_PHASES[c.phase] then return UNRELEASED end
    return nil
end

-- Quests ATT calls gone that the 2.17.0 review against Wowhead found in the game, or could not settle, so they stay marked.
local KEPT = {
    Vanilla = { [8411] = true },
    TBC = { [4485] = true, [4486] = true, [5652] = true, [5654] = true, [5656] = true, [5657] = true, [5680] = true,
            [7863] = true, [7864] = true, [7866] = true, [7867] = true, [8260] = true, [8261] = true, [8263] = true, [8264] = true },
    Forever = { [8411] = true, [5674] = true },
}

-- Keeps a reviewed quest open, and lists it so a later ATT release that agrees can retire it
local function review(rules, kept, keptBy)
    for id in pairs(kept) do
        if rules.ended[id] == NOT_IN_GAME then
            rules.ended[id] = nil
            keptBy.kept[#keptBy.kept + 1] = id
        else
            keptBy.unneeded[#keptBy.unneeded + 1] = id
        end
    end
end

-- A quest ATT lists twice is closed only when every copy is, as ATT shows a thing any copy offers.
local function endedCode(q, raids, open)
    local code = copyCode(q, raids)
    if not code then return nil end
    for _, alt in ipairs(q.alts or {}) do
        if not copyCode(alt, raids) then
            open[#open + 1] = q.id
            return nil
        end
    end
    return code
end

local function write(rules, path, label)
    local parts = { ("-- Generated by tools/build_att_rules.lua from AllTheThings (MIT), %s.\n"):format(label),
        "-- caps [questID] = { lowest, highest level it is offered at }, ended [questID] = 1 not in the game, 2 a world event\n",
        "-- that is not running, 3 the Scourge Invasion, 4 content not released here, daily [questID] = 1,\n",
        "-- faction [questID] = 1 Horde, 2 Alliance\nreturn {\n" }
    for _, part in ipairs({ "caps", "ended", "daily", "faction" }) do
        parts[#parts + 1] = part .. " = {\n"
        local t = rules[part]
        for _, id in ipairs(sortedKeys(t)) do
            local v = t[id]
            parts[#parts + 1] = type(v) == "table" and ("[%d]={%d,%d},\n"):format(id, v[1], v[2]) or ("[%d]=%d,\n"):format(id, v)
        end
        parts[#parts + 1] = "},\n"
    end
    parts[#parts + 1] = "}\n"
    local f = assert(io.open(path, "wb"), "cannot write " .. path)
    f:write(table.concat(parts))
    f:close()
    local back = assert(loadfile(path))()
    for _, part in ipairs({ "caps", "ended", "daily", "faction" }) do
        local n = 0
        for id, v in pairs(back[part]) do
            n = n + 1
            local want = rules[part][id]
            if type(want) == "table" then
                assert(type(v) == "table" and v[1] == want[1] and v[2] == want[2], ("%s: %s of quest %d changed on reload"):format(path, part, id))
            else
                assert(v == want, ("%s: %s of quest %d changed on reload"):format(path, part, id))
            end
        end
        assert(n == #sortedKeys(rules[part]), ("%s: %s row count changed on reload"):format(path, part))
    end
end

local function report(rules, open, path, keptBy)
    local byCode = {}
    for _, code in pairs(rules.ended) do byCode[code] = (byCode[code] or 0) + 1 end
    local lines = { ("-- att rules: %d level range(s), %d daily, %d faction(s); ended: %d not in the game, %d world event, %d Scourge Invasion, %d not released, written to %s")
        :format(#sortedKeys(rules.caps), #sortedKeys(rules.daily), #sortedKeys(rules.faction), byCode[NOT_IN_GAME] or 0,
                byCode[EVENT] or 0, byCode[INVASION] or 0, byCode[UNRELEASED] or 0, path) }
    if #open > 0 then
        table.sort(open)
        lines[#lines + 1] = "-- att ended left out, another copy of the quest is open: " .. table.concat(open, " ")
    end
    for _, k in ipairs({ { "kept", "-- att ended kept by review: " }, { "unneeded", "-- att review keep no longer needed: " } }) do
        local list = keptBy[k[1]]
        if #list > 0 then
            table.sort(list)
            lines[#lines + 1] = k[2] .. table.concat(list, " ")
        end
    end
    return lines
end

-- WoW Forever: an Era quest ATT's Forever data leaves out is read from its Era data, so raids Forever has not opened stay closed.
local function writeForever(forever, eraDir, outDir, foreverDir)
    local era = dofile(here .. "forever_att.lua")(eraDir).quests
    local rules, open = { caps = {}, ended = {}, daily = {}, faction = {} }, {}
    for id, q in pairs(forever) do
        rules.ended[id] = endedCode(q, false, open)
        rules.faction[id] = q.faction
    end
    for id, q in pairs(era) do
        if not forever[id] then
            rules.ended[id] = endedCode(q, true, open)
            rules.faction[id] = q.faction
        end
    end
    local keptBy = { kept = {}, unneeded = {} }
    review(rules, KEPT.Forever, keptBy)
    local path = outDir .. "/attRules.lua"
    write(rules, path, labelFor(foreverDir) .. " and " .. eraDir:gsub("[/\\]+$", ""):match("([^/\\]+)$"))
    return rules, report(rules, open, path, keptBy)
end

local attDir, outDir = ...
if not attDir then return writeForever end
assert(outDir, "usage: lua5.1 tools/build_att_rules.lua <AllTheThings db folder> <source folder>")
assert(not attDir:gsub("[/\\]+$", ""):match("Camelot$"), "WoW Forever's rules come from build_forever_supplement.lua --att")

local att = dofile(here .. "forever_att.lua")(attDir).quests
local rules, open = { caps = {}, ended = {}, daily = {}, faction = {} }, {}
for id, q in pairs(att) do
    if q.maxLevel then rules.caps[id] = { q.reqLevel or 0, q.maxLevel } end
    rules.ended[id] = endedCode(q, false, open)
    if q.daily then rules.daily[id] = 1 end
    rules.faction[id] = q.faction
end
local keptBy = { kept = {}, unneeded = {} }
review(rules, KEPT[attDir:gsub("[/\\]+$", ""):match("([^/\\]+)$")] or {}, keptBy)
local path = outDir .. "/attRules.lua"
write(rules, path, labelFor(attDir))
for _, line in ipairs(report(rules, open, path, keptBy)) do io.stderr:write(line .. "\n") end

local writeCrumbs = dofile(here .. "build_breadcrumbs.lua")
local n, links = writeCrumbs(att, outDir .. "/breadcrumbs.lua", attDir)
io.stderr:write(("-- breadcrumbs: %d quest(s) leading to %d follow-up(s), written to %s/breadcrumbs.lua\n"):format(n, links, outDir))
