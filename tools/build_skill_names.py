"""Writes Data/SkillNames_<flavor>.lua from the client's SkillLine table, every client locale, via wago.tools."""
import csv
import io
import os
import re
import sys
import time
import urllib.request
from pathlib import Path

LOCALES = ["enUS", "deDE", "esES", "esMX", "frFR", "itIT", "koKR", "ptBR", "ruRU", "zhCN", "zhTW"]
# The skill window's headings: weapons, class, armor, secondary skills, languages and professions
SKILL_WINDOW = {"6", "7", "8", "9", "10", "11"}
COLUMNS = ("ID", "DisplayName_lang", "CategoryID")


def checked(text, where):
    header = next(csv.reader(io.StringIO(text)), [])
    missing = [c for c in COLUMNS if c not in header]
    if missing:
        sys.exit(f"{where}: no {', '.join(missing)} column, refusing it")
    return text


def fetch(build, locale, cache):
    path = cache / f"SkillLine_{build}_{locale}.csv"
    if path.exists():
        return checked(path.read_bytes().decode("utf-8"), path)
    url = f"https://wago.tools/db2/SkillLine/csv?build={build}&locale={locale}"
    req = urllib.request.Request(url, headers={"User-Agent": "curl/8.0"})
    with urllib.request.urlopen(req, timeout=30) as r:
        body = r.read()
    text = checked(body.decode("utf-8"), url)
    tmp = path.with_suffix(".part")
    tmp.write_bytes(body)
    os.replace(tmp, path)
    time.sleep(0.3)
    return text


def names(text):
    found = {}
    for row in csv.DictReader(io.StringIO(text)):
        try:
            sid = int(row["ID"])
        except (KeyError, ValueError):
            continue
        name = row.get("DisplayName_lang", "")
        if row.get("CategoryID") in SKILL_WINDOW and name:
            if any(ord(ch) < 32 for ch in name):
                sys.exit(f"skill line {sid} has a control character in its name, refusing it")
            found[sid] = name
    return found


def gated_lines(data_file):
    text = Path(data_file).read_text(encoding="utf-8")
    block = re.search(r"^skill = \{\n(.*?)^\},", text, re.S | re.M)
    if not block:
        sys.exit(f"{data_file}: no skill table")
    return {int(v) // 10000 for v in re.findall(r"^\t\[\d+\]=(\d+),$", block.group(1), re.M)}


def lua_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    if len(sys.argv) != 5:
        sys.exit("usage: build_skill_names.py <build> <QuestAvailable data file> <output .lua> <cache dir>")
    build, data_file, out, cache = sys.argv[1], sys.argv[2], Path(sys.argv[3]), Path(sys.argv[4])
    cache.mkdir(parents=True, exist_ok=True)
    per = {loc: names(fetch(build, loc, cache)) for loc in LOCALES}
    english = per["enUS"]
    lacking = sorted(gated_lines(data_file) - set(english))
    if lacking:
        sys.exit(f"{data_file} gates on skill line(s) {lacking} with no enUS name in build {build}, refusing to write")
    for loc, table in per.items():
        if set(table) != set(english):
            sys.exit(f"{loc} names {len(table)} skill lines where enUS names {len(english)}, refusing to write")

    lines = [
        f"-- Generated by tools/build_skill_names.py from the client's SkillLine table, build {build}.",
        "-- Every skill the skill window can list, by locale and skill line id, from the table's display names.",
        "local _, ns = ...",
        "ns.SKILL_NAMES = {",
    ]
    for loc in LOCALES:
        table = per[loc]
        if loc != "enUS" and table == english:
            continue
        cells = ", ".join(f"[{sid}] = {lua_string(table[sid])}" for sid in sorted(table))
        lines.append(f"    {loc} = {{ {cells} }},")
    lines.append("}")
    tmp = out.with_suffix(".part")
    tmp.write_bytes(("\n".join(lines) + "\n").encode("utf-8"))
    os.replace(tmp, out)
    print(f"{out}: {len(english)} skill lines, {sum(1 for l in lines if l.startswith('    '))} locales")


if __name__ == "__main__":
    main()
