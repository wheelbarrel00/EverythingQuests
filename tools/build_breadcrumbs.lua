-- Writes breadcrumbs.lua into a source folder for build_questcoords.lua: each AllTheThings (MIT) breadcrumb quest and the quests it leads to.
--
--   lua5.1 tools/build_breadcrumbs.lua <AllTheThings db folder> <source folder>
--
-- Loaded through dofile with no arguments it returns the writer, which build_forever_supplement.lua calls with --att.

local here = debug.getinfo(1, "S").source:match("^@(.*[/\\])") or "tools/"

local function labelFor(dir)
    local folder = dir:gsub("[/\\]+$", ""):match("([^/\\]+)$") or dir
    local toc = io.open(dir .. "/../../AllTheThings.toc", "rb")
    local version = toc and toc:read("*a"):match("## Version:%s*([^\r\n]+)")
    if toc then toc:close() end
    return version and ("%s, db/%s"):format(version, folder) or ("db/" .. folder)
end

local function write(quests, path, attDir)
    local label = labelFor(attDir)
    local ids = {}
    for id, q in pairs(quests) do
        if q.breadcrumb and q.next then ids[#ids + 1] = id end
    end
    table.sort(ids)
    local rows, links = {}, 0
    local parts = { ("-- Generated by tools/build_breadcrumbs.lua from AllTheThings (MIT), %s. [breadcrumb questID] = { the quests it leads to }\nreturn {\n")
        :format(label) }
    for _, id in ipairs(ids) do
        local seen, to = {}, {}
        for _, t in ipairs(quests[id].next) do
            if t > 0 and t ~= id and not seen[t] then seen[t] = true; to[#to + 1] = t end
        end
        if #to > 0 then
            table.sort(to)
            rows[id] = to
            links = links + #to
            parts[#parts + 1] = ("[%d]={%s},\n"):format(id, table.concat(to, ","))
        end
    end
    parts[#parts + 1] = "}\n"
    local f = assert(io.open(path, "wb"), "cannot write " .. path)
    f:write(table.concat(parts))
    f:close()
    local back, n = assert(loadfile(path))(), 0
    for id, to in pairs(back) do
        n = n + 1
        assert(rows[id] and #rows[id] == #to, ("%s: quest %d changed on reload"):format(path, id))
        for i = 1, #to do assert(to[i] == rows[id][i], ("%s: quest %d changed on reload"):format(path, id)) end
    end
    local want = 0
    for _ in pairs(rows) do want = want + 1 end
    assert(n == want, path .. ": row count changed on reload")
    return n, links
end

local attDir, outDir = ...
if not attDir then return write end
assert(outDir, "usage: lua5.1 tools/build_breadcrumbs.lua <AllTheThings db folder> <source folder>")

local att = dofile(here .. "forever_att.lua")(attDir)
local n, links = write(att.quests, outDir .. "/breadcrumbs.lua", attDir)
io.stderr:write(("-- breadcrumbs: %d quest(s) leading to %d follow-up(s), written to %s/breadcrumbs.lua\n"):format(n, links, outDir))
